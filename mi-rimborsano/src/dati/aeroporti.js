export const PER_CODICE = Object.fromEntries(AEROPORTI.map((a) => [a[0], { codice: a[0], nome: a[1], lat: a[2], lon: a[3], ue: a[4] }]));

/** Distanza ortodromica in km (raggio medio terrestre 6.371 km). */
export function distanzaKm(da, a) {
  const r = (g) => (g * Math.PI) / 180;
  const p = PER_CODICE[da];
  const q = PER_CODICE[a];
  if (!p || !q) return null;
  const dlat = r(q.lat - p.lat);
  const dlon = r(q.lon - p.lon);
  const h = Math.sin(dlat / 2) ** 2 + Math.cos(r(p.lat)) * Math.cos(r(q.lat)) * Math.sin(dlon / 2) ** 2;
  return Math.round(2 * 6371 * Math.asin(Math.sqrt(h)));
}
